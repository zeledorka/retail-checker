/**
 * Regenerates supabase/seed.sql from Dev 2's hand-written fallback cases (scenarios/src/prepared-cases.ts).
 * Every case is validated with Dev 1's startRound() first, so a seeded case can never be rejected mid-game.
 *
 *   npx tsx scripts/dev/make-seed.ts          (from ai-courtroom/)
 *
 * A/B = the case's first two candidate interpretations. This is a FALLBACK choice for testing: the real pipeline
 * (prepareNewRound) picks the pair with independent opinions + a blind checker. image_url is left NULL (no fake URL).
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { PREPARED_CASES } from '../../../scenarios/src/prepared-cases';
import { startRound } from '../../../ai/src/round';

const BACKUPS = 1; // the last N cases are only used once the others run out

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows: string[] = [];

PREPARED_CASES.forEach((c, i) => {
  const [a, b] = c.interpretations;
  if (!a || !b) throw new Error(`${c.id}: needs at least two interpretations`);
  const scenario = {
    title: c.title,
    description: c.description,
    evidence: c.evidence,
    interpretationA: `${a.label}: ${a.description}`,
    interpretationB: `${b.label}: ${b.description}`,
  };
  const check = startRound({ roundId: `seed-check-${i}`, scenario });
  if (!check.ok) throw new Error(`${c.id}: rejected by the AI engine: ${check.error.message}`);

  const isBackup = i >= PREPARED_CASES.length - BACKUPS;
  rows.push(
    `(${q(c.id)}, ${q(scenario.title)}, ${q(scenario.description)}, ${q(scenario.interpretationA)}, ` +
    `${q(scenario.interpretationB)}, ${q(JSON.stringify(scenario.evidence))}::jsonb, ${c.imagePath ? q(c.imagePath) : 'null'}, ${isBackup})`,
  );
});

const sql = `-- GENERATED by scripts/dev/make-seed.ts from scenarios/src/prepared-cases.ts. Do not edit by hand.
-- Run in the Supabase SQL Editor after the migrations. Safe to re-run (updates existing ids).
insert into public.cases (id, title, description, interpretation_a, interpretation_b, evidence_json, image_url, is_backup)
values
${rows.join(',\n')}
on conflict (id) do update set
  title = excluded.title, description = excluded.description,
  interpretation_a = excluded.interpretation_a, interpretation_b = excluded.interpretation_b,
  evidence_json = excluded.evidence_json, image_url = excluded.image_url, is_backup = excluded.is_backup;
`;

const out = path.join(__dirname, '../../supabase/seed.sql');
writeFileSync(out, sql);
console.log(`Wrote ${rows.length} cases (${BACKUPS} backup) to ${out}`);
